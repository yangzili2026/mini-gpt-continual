FILLERS_Q = ["另外", "还有一个问题", "顺便问一下", "那", "好的"]
FILLERS_A = ["这个问题问得很好。", "这是很多同学的共性问题。", "我们分两个层面来看。", "简单说要分情况讨论。"]

def build_qa(topic_key):
    t = TOPICS[topic_key]
    opener = random.choice(t["openers"])
    # 提问方追问 2~3 轮，回答方对应 2~3 轮
    k = random.randint(2, 3)
    qs = random.sample(t["advancers_q"], k)
    ans = random.sample(t["answers"], k)
    fup = random.sample(t["followups_q"], k)
    dialogue = [("提问者", opener)]
    if random.random() < 0.5:
        dialogue.append(("讲评人", random.choice(FILLERS_A)))
    for i in range(k):
        dialogue.append(("讲评人", ans[i]))
        dialogue.append(("提问者", fup[i]))
        if i < k - 1:
            dialogue.append(("提问者", qs[i + 1]))
    # 收尾
    dialogue.append(("讲评人", random.choice([
        "总结一下：关键是先把核心实验做扎实，论述部分再围绕证据展开，你的论文就会很有说服力。",
        "整体思路就是这样，你先改，改完我们再过一遍。",
        "记住，学术写作的核心是让证据替你说服审稿人，其余的只是组织方式问题。"
    ])))
    return dialogue

def score_qa(turns, topic_key):
    text = "".join(x[1] for x in turns)
    import statistics
    lens = [len(x[1]) for x in turns]
    mean_len = statistics.mean(lens)
    # 专业性：术语密度
    terms = ["实验", "方法", "数据", "分析", "结果", "验证", "模型", "样本", "假设", "指标", "消融", "基线", "显著", "方差", "审稿"]
    term_hits = sum(1 for w in terms if w in text)
    professionalism = min(5.0, round(2.8 + 0.22 * term_hits + random.uniform(-0.2, 0.2), 1))
    # 逻辑性：轮次越多、结构越完整分越高
    logic = min(5.0, round(2.5 + 0.4 * len(turns) + random.uniform(-0.2, 0.2), 1))
    # 深度：平均句长体现论述充分性
    depth = min(5.0, round(2.0 + mean_len * 0.09 + random.uniform(-0.2, 0.2), 1))
    # 流畅度：句长偏离度小则流畅
    fluency = min(5.0, round(5.0 - statistics.pstdev(lens) * 0.02 + random.uniform(-0.1, 0.1), 1))
    overall = round(professionalism * 0.3 + logic * 0.25 + depth * 0.25 + fluency * 0.2, 1)
    return {
        "专业性(1-5)": max(1.0, professionalism),
        "逻辑性(1-5)": max(1.0, logic),
        "深度(1-5)": max(1.0, depth),
        "流畅度(1-5)": max(1.0, fluency),
        "综合质量分(1-5)": max(1.0, min(5.0, overall)),
    }

def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))
    n = 120
    topic_keys = list(TOPICS.keys())
    records = []
    for i in range(n):
        tk = random.choice(topic_keys)
        turns = build_qa(tk)
        scores = score_qa(turns, tk)
        records.append({
            "id": f"acad-{i+1:04d}",
            "场景": "学术论文讲评",
            "话题": tk,
            "对话轮数": len(turns),
            "对话内容": turns,
            **scores,
        })

    # JSONL 备份
    jsonl_path = os.path.join(out_dir, "学术讲评论文问答语料_带评分.jsonl")
    with open(jsonl_path, "w", encoding="utf-8") as f:
        for r in records:
            r2 = dict(r)
            r2["对话内容"] = "\n".join(f"{s}：{t}" for s, t in r["对话内容"])
            f.write(json.dumps(r2, ensure_ascii=False) + "\n")

    # Word 文档
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "宋体"
    style.font.size = Pt(11)

    title = doc.add_heading("学术论文讲评问答语料（带评分）", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = doc.add_paragraph(f"共 {len(records)} 条长对话语料｜评分维度：专业性、逻辑性、深度、流畅度（各 1–5 分），综合质量分为加权平均。")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph("评分权重：专业性 30% + 逻辑性 25% + 深度 25% + 流畅度 20%。")

    for r in records:
        h = doc.add_heading(f"{r['id']}｜话题：{r['话题']}｜轮数：{r['对话轮数']}", level=2)
        meta = doc.add_paragraph()
        run = meta.add_run(
            f"专业性 {r['专业性(1-5)']} ｜ 逻辑性 {r['逻辑性(1-5)']} ｜ 深度 {r['深度(1-5)']} ｜ "
            f"流畅度 {r['流畅度(1-5)']} ｜ 综合质量分 {r['综合质量分(1-5)']}"
        )
        run.bold = True
        run.font.color.rgb = RGBColor(0x1F, 0x4E, 0x79)
        for speaker, text in r["对话内容"]:
            para = doc.add_paragraph()
            s_run = para.add_run(f"{speaker}：")
            s_run.bold = True
            para.add_run(text)
        doc.add_paragraph()

    docx_path = os.path.join(out_dir, "学术讲评论文问答语料_带评分.docx")
    doc.save(docx_path)

    print(f"生成 {len(records)} 条语料")
    print(docx_path)
    print(jsonl_path)

if __name__ == "__main__":
    main()
