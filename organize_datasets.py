def overall(s):
    return round(sum(s[k] * W[k] for k in W), 1)

CATEGORY_ORDER = ["通用中文预训练", "对话语料", "问答语料", "百科知识", "新闻媒体", "行业领域", "金融领域", "通用中文混合", "通用中英双语", "英文预训练", "多模态", "文学古籍"]

def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))

    # ---------- Word ----------
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "宋体"
    style.font.size = Pt(11)

    title = doc.add_heading("中文训练语料数据集整理与评分（25个）", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = doc.add_paragraph("来源：用户提供的 CCI 3.0.txt 清单｜评分视角：作为语料喂给自己的小型 GPT")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph(
        "评分维度与权重：中文纯度 20%（是否纯中文/中英比例）＋ 质量保障 25%（清洗、去重、标签、防泄露）＋ "
        "规模 20%（体量与可持续性）＋ 易用性 20%（格式、文档、上手成本）＋ 训练适配度 15%（对『训练自己的小型 GPT』的实用程度）。每项 1–5 分。"
    )
    doc.add_paragraph("注：原始清单中各数据集的链接均为『数据集地址』占位符，本文档保留该项，实际地址可在 HuggingFace Datasets / GitHub / OpenDataLab 按名称检索获取。")

    for cat in CATEGORY_ORDER:
        items = [d for d in DATA if d[1] == cat]
        if not items:
            continue
        doc.add_heading(f"■ {cat}", level=1)
        for (name, _, date, org, scale, desc, scores, comment) in items:
            doc.add_heading(name, level=2)
            info = doc.add_paragraph()
            info.add_run(f"发布时间：{date}　｜　发布机构：{org}　｜　规模：{scale}").bold = True
            doc.add_paragraph(f"简介：{desc}")
            doc.add_paragraph("地址：数据集地址（原文占位符，需检索补充）")
            sline = doc.add_paragraph()
            run = sline.add_run(" ｜ ".join(f"{k} {scores[k]}" for k in W) + f" ｜ ★ 综合 {overall(scores)}")
            run.bold = True
            run.font.color.rgb = RGBColor(0x1F, 0x4E, 0x79)
            doc.add_paragraph(f"点评：{comment}")

    doc.add_heading("■ 选用建议（针对小型 GPT）", level=1)
    for tip in [
        "主语料（量大管饱）：CCI 3.0、Chinese Fineweb Edu、MAP-CC、ChineseWebText（取高分段）——按分数阈值切片使用。",
        "小型模型友好（体量小、开箱即用）：TigerResearch/pretrain_zh（约56G）、wikipedia-cn 精筛版、CLUECorpus2020。",
        "对话/问答能力（与你自造的唠嗑、讲评语料互补）：LCCC + Baike2018qa。",
        "按需调味：BBT-FinCorpus（金融）、OpenNewsArchive/蜜巢花粉（新闻）、Chinese-Poetry（古文）。",
        "不建议：WanJuan2.0（纯英文）、TaiSu/OmniCorpus/WanJuan1.0（多模态为主，纯文本训练性价比低）。",
        "别忘了配比：预训练语料 ≠ 越多越好，小型 GPT 建议高质量子集 10~50GB 起步，对话/问答类单独留作 SFT 阶段。",
    ]:
        doc.add_paragraph(tip, style="List Bullet")

    docx_path = os.path.join(out_dir, "中文训练语料数据集整理与评分.docx")
    doc.save(docx_path)

    # ---------- Excel 总表 ----------
    import openpyxl
    from openpyxl.styles import Font, PatternFill
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "数据集总表"
    headers = ["排名", "名称", "类别", "发布时间", "发布机构", "规模", "中文纯度", "质量保障", "规模分", "易用性", "训练适配度", "综合分", "简介"]
    ws.append(headers)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="D9E1F2")
    ranked = sorted(DATA, key=lambda d: -overall(d[6]))
    for rank, d in enumerate(ranked, 1):
        name, cat, date, org, scale, desc, scores, _ = d
        ws.append([rank, name, cat, date, org, scale,
                   scores["中文纯度"], scores["质量保障"], scores["规模"], scores["易用性"], scores["训练适配度"],
                   overall(scores), desc])
    ws.column_dimensions["B"].width = 34
    ws.column_dimensions["M"].width = 60
    ws.freeze_panes = "A2"
    xlsx_path = os.path.join(out_dir, "中文训练语料数据集总表_带评分.xlsx")
    wb.save(xlsx_path)

    print(docx_path)
    print(xlsx_path)
    for rank, d in enumerate(ranked, 1):
        print(rank, d[0], overall(d[6]))

if __name__ == "__main__":
    main()
