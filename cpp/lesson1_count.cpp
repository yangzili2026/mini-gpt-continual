// ============================================================
// C++ 造大语言模型 · 第1课：让程序"吃下"训练语料
// ------------------------------------------------------------
// 我们的目标：不用任何现成的 AI 库，纯 C++ 写出一个能自己造句的模型。
// 第一课只做一件事：把 train_text.txt（约 150 万字节英文）读进来，
// 数清楚每个字节（字符）出现了多少次。
// ============================================================
// 本课标注说明（以后每课都沿用这套符号）：
//   【难】   = 有点复杂，没学过或忘了，重点看注释
//   【易错】 = 会写但容易出错，写的时候小心
//   【记】   = 保险起见标注，照抄即可
// ============================================================
#include <bits/stdc++.h>   // 万能头：GESP 竞赛同款，一个头文件包含全部标准库
using namespace std;

int main() {
    // ---------- 1. 读文件 ----------
    // 【易错】必须加 ios::binary（二进制模式）。
    //   Windows 的文本模式会偷偷改动换行符，导致字节数和真实文件对不上。
    ifstream fin("train_text.txt", ios::binary);

    // 【易错】读完要检查是否成功，否则后面全是白费
    if (!fin) {
        cout << "找不到 train_text.txt！" << endl;
        return 1;
    }

    // 【难】把文件的全部字节一口气装进 vector。
    //   istreambuf_iterator 是"输入流迭代器"：可以理解成一个
    //   不停从文件里吐字节出来的"水龙头"，从头到尾接着接就行。
    //   这一行等价于：循环 fin.get() 直到文件末尾，逐个 push_back。
    //   自己写的话用循环也行，这个写法只是一行搞定。
    vector<unsigned char> data(
        (istreambuf_iterator<char>(fin)),   // 水龙头：从这里开始接
        istreambuf_iterator<char>());       // 空迭代器：代表"接到没水为止"

    fin.close();   // 【记】好习惯：用完就关

    cout << "读入 " << data.size() << " 个字节" << endl << endl;

    // ---------- 2. 看看原料长什么样 ----------
    cout << "前 200 个字符预览：" << endl;
    for (size_t i = 0; i < 200 && i < data.size(); i++)
        cout << data[i];
    cout << endl << endl;

    // ---------- 3. 数字节频率 ----------
    // 一个字节只有 256 种可能（0~255），所以开一个 256 格的数组。
    // 每读到一个字节，就把它对应的那一格 +1。这叫"直方图统计"。
    vector<long long> count(256, 0);   // 【记】long long 防止大文件计数溢出

    int used = 0;                      // 记录实际用到了几种字节
    for (unsigned char c : data) {     // 范围for：逐个取出字节
        if (count[c] == 0) used++;     // 第一次见到的字节
        count[c]++;
    }
    cout << "这篇语料一共用到 " << used << " 种不同的字节" << endl << endl;

    // ---------- 4. 打印出现最多的 15 个字节 ----------
    // 把 256 个字节按出现次数从大到小排个序
    vector<int> order(256);
    for (int i = 0; i < 256; i++) order[i] = i;

    // 【易错】sort 第三个参数是比较函数：
    //   返回 true 表示 a 应该排在 b 前面，所以"从大到小"要写 count[a] > count[b]
    sort(order.begin(), order.end(),
         [&](int a, int b){ return count[a] > count[b]; });

    cout << "出现次数排行榜 Top 15：" << endl;
    for (int k = 0; k < 15; k++) {
        int c = order[k];
        // 【易错】三目运算符：可打印字符才显示原样，否则显示 '?'
        char shown = (c >= 32 && c <= 126) ? (char)c : '?';
        printf("  第%2d名: 字节 %3d ('%c')  出现了 %lld 次，占 %.2f%%\n",
               k + 1, c, shown,
               count[c], 100.0 * count[c] / data.size());
    }

    // ---------- 5. 一个重要的设计决定 ----------
    // 还记得 Python 里的 tokenizer 吗？它把英文切成几万个"词元"(token)，
    // 比如 "unbelievable" 切成 un + believ + able。效率高但规则复杂。
    //
    // 我们换一种最笨但最透明的办法：【一个字节 = 一个词元】。
    // 词表固定 256，任何文本都能表示，一行规则都不用写。
    // 代价是模型得自己学会把字节拼成单词——正好让它多学一点东西。
    cout << endl << "我们的词表 = 全部 256 个字节。就这么简单。" << endl;
    return 0;
}
